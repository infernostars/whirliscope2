"""Extract file-scope `public` C functions."""

import argparse
from pathlib import Path
import re
import sys


# Keep comments, strings and preprocessor lines indivisible so their contents
# cannot be mistaken for declarations or brace delimiters.
TOKEN = re.compile(
    r'(?P<directive>^[ \t]*\#(?:[^\n\\]|\\[^\n]|\\\n)*)'
    r'|(?P<comment>/\*.*?\*/|//(?:\\\n|[^\n])*)'
    r'|(?P<string>"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\')'
    r'|(?P<space>[^\S\n]+|\n)'
    r'|(?P<word>[a-zA-Z_][a-zA-Z_0-9]*)'
    r'|(?P<punct>.)',
    re.MULTILINE | re.DOTALL,
)
GENERATED = "// Generated by scripts/auto_headers.py; do not edit.\n"
PUBLIC_MARKER = re.compile(r"/\*+\s*@public\s*\*+/")


def generate(source: str, name: str, template=None) -> str:
    tokens = [t for t in TOKEN.finditer(source)
              if t.lastgroup not in {"space", "comment"}]
    lines = []
    depth = 0
    exported = False
    i = 0

    def fail(token, message):
        line = source.count("\n", 0, token.start()) + 1
        raise ValueError(f"{name}:{line}: {message}")

    while i < len(tokens):
        token = tokens[i]
        value = token.group()
        if token.lastgroup == "directive":
            # Preserve conditional exports, including branches with no exports.
            if depth == 0 and re.match(r"\s*#\s*(if|ifdef|ifndef|elif|elifdef|elifndef|else|endif)\b", value):
                lines.append(value.strip())
        elif token.lastgroup == "string":
            pass
        elif value == "public" and depth == 0:
            start = token
            declaration = []
            nesting = []
            i += 1
            while i < len(tokens):
                token = tokens[i]
                value = token.group()
                if token.lastgroup == "directive":
                    fail(token, "preprocessor directives inside public signatures are unsupported")
                if not nesting and value in {";", "{"}:
                    break
                if value in {"(", "["}:
                    nesting.append(value)
                elif value in {")", "]"}:
                    if not nesting or nesting.pop() != {")": "(", "]": "["}[value]:
                        fail(token, "unbalanced public signature")
                declaration.append(value)
                i += 1
            else:
                fail(start, "unterminated public function")
            signature = " ".join(declaration)
            # Support ordinary C function declarators, including callback
            # parameters and attributes; reject storage and variable exports.
            if (not re.search(r"\b\w+\s+\w+\s*\(|\*\s*\w+\s*\(", signature)
                    or any(t in declaration for t in {"=", "static", "typedef", "{"})):
                fail(start, "public must mark a non-static function declaration or definition")
            # Preserve punctuation adjacency (e.g. ..., [[attributes]], ->)
            # and literal contents; only comments and the marker disappear.
            raw = source[start.end():token.start()]
            raw = TOKEN.sub(lambda t: " " if t.lastgroup == "comment" else t.group(), raw)
            lines.append(raw.strip() + ";")
            exported = True
            if value == "{":
                depth += 1
        elif value == "{":
            depth += 1
        elif value == "}":
            depth -= 1
        i += 1
    declarations = "\n".join(lines) + "\n" if exported else ""
    if template is not None:
        markers = list(PUBLIC_MARKER.finditer(template))
        if len(markers) > 1:
            raise ValueError(f"{name}: template must contain at most one @public marker")
        if markers:
            body = PUBLIC_MARKER.sub(lambda _: declarations.rstrip(), template)
        else:
            body = template.rstrip() + "\n\n" + declarations
        return GENERATED + body.rstrip() + "\n"
    if declarations:
        return GENERATED + "#pragma once\n\n" + declarations
    return ""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, nargs="?")
    parser.add_argument("output", type=Path, nargs="?")
    parser.add_argument("--clean", type=Path, nargs="+", metavar="HEADER")
    args = parser.parse_args()
    try:
        if args.clean:
            for path in args.clean:
                if path.exists() and path.read_text().startswith(GENERATED):
                    path.unlink()
            return 0
        if args.source is None or args.output is None:
            parser.error("source and output are required unless --clean is used")
        template = args.source.with_suffix(".template.h")
        if not args.source.exists() and not template.exists():
            raise ValueError(f"{args.source}: source and template are both missing")
        result = generate(
            args.source.read_text() if args.source.exists() else "",
            str(args.source), template.read_text() if template.exists() else None)
        # Remove headers left by the previous .auto.h naming convention.
        legacy = args.source.with_suffix(".auto.h")
        if legacy != args.output and legacy.exists() and legacy.read_text().startswith(GENERATED):
            legacy.unlink()
        existing = args.output.read_text() if args.output.exists() else None
        if existing is not None and not existing.startswith(GENERATED):
            if result:
                raise ValueError(f"{args.output}: handwritten header exists; move it to {template}")
            return 0
        if not result:
            args.output.unlink(missing_ok=True)
            return 0
        if result == existing:
            return 0
        # Atomic replacement leaves no partially written header after a failure.
        temporary = args.output.with_suffix(args.output.suffix + ".tmp")
        temporary.write_text(result)
        temporary.replace(args.output)
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
